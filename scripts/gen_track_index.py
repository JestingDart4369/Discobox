#!/usr/bin/env python3
"""
gen_track_index.py — turn the SD card's index.txt files into a C header, so the
firmware knows WHAT is playing (the DFPlayer itself only reports numbers).

Source: one index.txt per SD folder, written by the microssd tool:
    <sd_root>/02/index.txt
      Nr | File | Title | Uploader | Duration | URL
      # Run 2026-10-23 14:17 — https://...           (comment, ignored)
      001 | 001 - Kool & ... .mp3 | Kool & The Gang - Celebration | KoolandthegangShow | 4:17 | https://...

Output: include/Audio/Track_Index_Data.h  (gitignored — generated)
    const TrackInfo TRACKS[] = { { 2, 1, 257, "Kool & The Gang - Celebration", "KoolandthegangShow" }, ... };

Runs automatically before every `pio run` (extra_scripts in platformio.ini),
reading the folder set by `custom_sd_root`. Also runs by hand:
    python3 scripts/gen_track_index.py ../microssd/microssd_Files include/Audio/Track_Index_Data.h

Missing folder or file -> an EMPTY table (the build still works, nothing is named).
Later lines win, so re-running the downloader never creates duplicates.
"""
import re
import sys
from pathlib import Path

MAX_TITLE = 60      # bytes, cut at a UTF-8 boundary (keeps log lines < 128 chars)
MAX_ARTIST = 32

# "(Official Video)", "[4K]", "(Audio)", "＊Resub＊" ... are noise on a 128-char log line
NOISE = re.compile(r"official|video|audio|lyrics?|\bhd\b|\bhq\b|\b4k\b|remaster|legendado|resub|visualizer|clip", re.I)
GROUP = re.compile(r"\s*[\(\[（【＊][^\)\]）】＊]*[\)\]）】＊]")


def clean_title(title: str) -> str:
    out = GROUP.sub(lambda m: "" if NOISE.search(m.group(0)) else m.group(0), title)
    out = re.sub(r"\s*[-–|┆]\s*(HQ.?HD|Lyrics.*|Official.*)$", "", out, flags=re.I)   # " - HQ/HD", "┆ Lyrics", " - Official Music Video"
    out = re.sub(r"\s*Legendado.*$", "", out, flags=re.I)                               # "Legendado em PT-BR" (subtitle note)
    out = re.sub(r"\s{2,}", " ", out).strip(" -|")
    return out or title.strip()


def clean_artist(uploader: str) -> str:
    return re.sub(r"\s*-\s*Topic$", "", uploader).strip()


def cut_utf8(text: str, max_bytes: int) -> str:
    data = text.encode("utf-8")
    if len(data) <= max_bytes:
        return text
    data = data[: max_bytes - 3]
    while data and (data[-1] & 0xC0) == 0x80:    # don't split a multi-byte character
        data = data[:-1]
    if data and data[-1] >= 0xC0:
        data = data[:-1]
    return data.decode("utf-8", "ignore").rstrip() + "..."


def seconds(duration: str) -> int:
    try:
        parts = [int(p) for p in duration.strip().split(":")]
    except ValueError:
        return 0
    total = 0
    for p in parts:
        total = total * 60 + p
    return total if total < 65536 else 65535


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_index(sd_root: Path):
    tracks = {}                                    # (folder, track) -> (secs, title, artist)
    if not sd_root.is_dir():
        return tracks
    for folder_dir in sorted(p for p in sd_root.iterdir() if p.is_dir() and re.fullmatch(r"\d\d", p.name)):
        index = folder_dir / "index.txt"
        if not index.is_file():
            continue
        folder = int(folder_dir.name)
        for line in index.read_text(encoding="utf-8", errors="replace").splitlines():
            if not line.strip() or line.startswith("#") or line.startswith("Nr |"):
                continue
            fields = [f.strip() for f in line.split(" | ")]
            if len(fields) < 5 or not fields[0].isdigit():
                continue
            track = int(fields[0])
            if not (1 <= folder <= 99 and 1 <= track <= 255):
                continue
            tracks[(folder, track)] = (
                seconds(fields[4]),
                cut_utf8(clean_title(fields[2]), MAX_TITLE),
                cut_utf8(clean_artist(fields[3]), MAX_ARTIST),
            )
    return tracks


def render(tracks, sd_root: Path) -> str:
    lines = [
        "// GENERATED by scripts/gen_track_index.py — do not edit, changes are overwritten.",
        f"// Source: {sd_root.as_posix()}/NN/index.txt   ({len(tracks)} tracks)",
        "#pragma once",
        "#define TRACK_INDEX_GENERATED 1",
        "",
        "// folder, track, seconds, title, artist (uploader)",
        "const TrackInfo TRACKS[] = {",
    ]
    for (folder, track), (secs, title, artist) in sorted(tracks.items()):
        lines.append(f"  {{ {folder:2d}, {track:3d}, {secs:4d}, {c_string(title)}, {c_string(artist)} }},")
    if not tracks:
        lines.append("  { 0, 0, 0, \"\", \"\" },   // empty: no index found (see custom_sd_root)")
    lines += [
        "};",
        f"const uint16_t TRACK_COUNT = {len(tracks)};",
        "",
    ]
    return "\n".join(lines)


def generate(sd_root: Path, out_file: Path) -> int:
    tracks = read_index(sd_root)
    text = render(tracks, sd_root)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    if not out_file.exists() or out_file.read_text(encoding="utf-8") != text:   # unchanged -> no rebuild
        out_file.write_text(text, encoding="utf-8")
    return len(tracks)


# ── PlatformIO: runs as `extra_scripts = pre:scripts/gen_track_index.py` ─────
try:
    Import("env")  # noqa: F821  (only defined inside PlatformIO)
except NameError:
    env = None

if env is not None:
    project = Path(env.subst("$PROJECT_DIR"))
    root_opt = env.GetProjectOption("custom_sd_root", "../microssd/microssd_Files")
    sd_root = (project / root_opt).resolve()
    count = generate(sd_root, project / "include" / "Audio" / "Track_Index_Data.h")
    if count:
        print(f"Track index: {count} tracks from {sd_root}")
    else:
        print(f"Track index: no index.txt found under {sd_root} - track names disabled (set custom_sd_root)")
elif __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_track_index.py <sd_root> <out.h>")
    n = generate(Path(sys.argv[1]), Path(sys.argv[2]))
    print(f"{n} tracks -> {sys.argv[2]}")
